#include <stdio.h>

int main() {
    int itemPrice = 150; // Declare itemPrice and assign a value
    int shippingCost = 30; //Declare shippingCost and assign a value
    int sum; //  Create an int variable named sum
    sum = itemPrice + shippingCost; //  Calculate total cost and store in sum
    printf("Total cost: %d\n", sum); // Print the total cost using printf

    return 0;
}



